describe('arXiv parsing', () => {
  it('parses the Atom API response', () => {
    const m = parseArxivAtom(fixture('arxiv-atom.xml'))!;
    expect(m.title).toBe('Distributionally Robust Receive Combining');
    expect(m.authors).toEqual(['Shixiong Wang', 'Wei Dai', 'Geoffrey Ye Li']);
    expect(m.abstract).toMatch(/^This article investigates signal estimation/);
    expect(m.published?.toISOString()).toBe('2024-01-22T20:20:48.000Z');
    expect(m.pdfUrl).toBe('https://arxiv.org/pdf/2401.12345v3');
    expect(m.doi).toBe('10.1109/TSP.2025.3582082');
    expect(m.journalRef).toBe('IEEE Transactions on Signal Processing, June 2025');
    expect(m.category).toBe('eess.SP');
  });

  it('reports API errors and empty results', () => {
    expect(() => parseArxivAtom(fixture('arxiv-error.xml'))).toThrow('arXiv: incorrect id format for hep-th/99010');
    expect(parseArxivAtom('<feed xmlns="http://www.w3.org/2005/Atom"><title>x</title></feed>')).toBeNull();
  });

  it('parses citation tags from the abs page', () => {
    const m = parseArxivAbsPage(fixture('arxiv-abs-old.html'), 'https://arxiv.org/abs/hep-th/9901001')!;
    expect(m.title).toBe('String Junctions and Their Duals in Heterotic String Theory');
    expect(m.authors).toEqual(['Yosuke Imamura']);
    expect(m.doi).toBe('10.1143/PTP.101.1155');
    expect(m.abstract).toMatch(/^We explicitly give the correspondence/);
  });

  it('cleans LaTeXML HTML: no title/authors/abstract, math kept, images absolute, footnotes inline', () => {
    const html = arxivHtmlContent(fixture('arxiv-latexml.html'), 'https://arxiv.org/html/2401.12345');
    expect(html).not.toMatch(/Shixiong|Imperial|<h1|Report issue|Generated by LaTeXML|investigates signal/);
    expect(html).toContain('<h2><span>I </span>Introduction</h2>');
    expect(html).toContain('<math display="inline"><semantics><mi>F</mi></semantics></math>-norm');
    expect(html).toContain('<img src="https://arxiv.org/html/2401.12345v3/x1.png" alt="Refer to caption">');
    expect(html).toContain('see Theorem <span>2</span> and prior work<small> (See the survey by Smith.)</small>.');
    expect(html).toContain('<th>Combiner</th><td>MSE</td>');
  });
});

describe('extractUrl for arXiv (mocked network)', () => {
  it('uses the API metadata and the HTML version, abstract first', async () => {
    mockFetch([
      [/^https:\/\/export\.arxiv\.org\/api\/query\?id_list=2401\.12345&/, { body: fixture('arxiv-atom.xml'), type: 'application/atom+xml' }],
      ['https://arxiv.org/html/2401.12345', { body: fixture('arxiv-latexml.html') }],
    ]);
    const r = await extractUrl('https://arxiv.org/abs/2401.12345');
    expect(r.type).toBe('paper');
    expect(r.title).toBe('Distributionally Robust Receive Combining');
    expect(r.author).toBe('Shixiong Wang, Wei Dai, Geoffrey Ye Li');
    expect(r.siteName).toBe('arXiv');
    expect(r.canonicalUrl).toBe('https://arxiv.org/abs/2401.12345');
    expect(r.html.startsWith('<section><h2>Abstract</h2><p>This article investigates')).toBe(true);
    expect(r.html).toContain('Introduction</h2>');
    expect(r.paper).toMatchObject({
      arxivId: '2401.12345',
      authors: ['Shixiong Wang', 'Wei Dai', 'Geoffrey Ye Li'],
      year: 2024,
      pdfUrl: 'https://arxiv.org/pdf/2401.12345v3',
      doi: '10.1109/TSP.2025.3582082',
      venue: 'IEEE Transactions on Signal Processing, June 2025',
    });
    expect(r.paper?.abstract).toMatch(/^This article/);
    expect(r.file).toBeNull();
  });

  it('falls back to the abs page when rate-limited and to PDF text when there is no HTML', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout'], shouldAdvanceTime: true, advanceTimeDelta: 500 });
    const pdf = makePdf({
      pages: [[
        { text: 'String Junctions', y: 720, size: 18 },
        { text: 'Abstract', y: 680, size: 11 },
        { text: 'We explicitly give the correspondence between spectra.', y: 660 },
        { text: 'References', y: 600 },
        { text: '[1] A. Author, Some paper.', y: 586 },
      ]],
    });
    const spy = mockFetch([
      [/^https:\/\/export\.arxiv\.org\/api\/query/, { status: 429, body: 'Rate exceeded' }],
      ['https://arxiv.org/abs/hep-th/9901001', { body: fixture('arxiv-abs-old.html') }],
      ['https://arxiv.org/html/hep-th/9901001', { status: 404, body: 'No HTML' }],
      ['https://arxiv.org/pdf/hep-th/9901001', { body: pdf, type: 'application/pdf' }],
    ]);
    const r = await extractUrl('https://arxiv.org/abs/hep-th/9901001');
    vi.useRealTimers();
    expect(r.title).toBe('String Junctions and Their Duals in Heterotic String Theory');
    expect(r.paper).toMatchObject({ arxivId: 'hep-th/9901001', doi: '10.1143/PTP.101.1155', year: 1999 });
    expect(r.html).toContain('<section><h2>Abstract</h2><p>We explicitly give');
    expect(r.html).toContain('<h2 data-page="1">Page 1</h2>');
    expect(r.file?.contentType).toBe('application/pdf');
    expect(spy.mock.calls.filter(([u]) => String(u).startsWith('https://export.arxiv.org')).length).toBe(2);
  });
});

describe('DOI', () => {
  it.each([
    ['10.1371/journal.pone.0115253', '10.1371/journal.pone.0115253'],
    ['doi:10.7554/eLife.00013', '10.7554/eLife.00013'],
    ['https://doi.org/10.1145/3290605.3300233', '10.1145/3290605.3300233'],
    ['https://dx.doi.org/10.1000/xyz%2F123', '10.1000/xyz/123'],
    ['10.1000/abc.', '10.1000/abc'],
  ])('parses %s', (input, doi) => expect(parseDoi(input)).toBe(doi));

  it.each(['https://example.com/10.1000/x', '10.12/x', 'hello'])('rejects %s', (input) => expect(parseDoi(input)).toBeNull());

  it('converts JATS abstracts', () => {
    expect(jatsToHtml('<jats:title>Abstract</jats:title><jats:p>Some <jats:italic>text</jats:italic> with H<jats:sub>2</jats:sub>O.</jats:p><jats:sec><jats:title>Methods</jats:title><jats:p>We did it.</jats:p></jats:sec>')).toBe(
      '<p>Some <em>text</em> with H<sub>2</sub>O.</p><h3>Methods</h3><p>We did it.</p>',
    );
    expect(jatsToHtml('Plain abstract')).toBe('<p>Plain abstract</p>');
  });

  it('parses Crossref metadata (real response)', () => {
    const cr = parseCrossref(fixtureJson('crossref-elife.json').message, '10.7554/eLife.00013');
    expect(cr.title).toBe('A bacterial sulfonolipid triggers multicellular development in the closest living relatives of animals');
    expect(cr.authors[0]).toBe('Rosanna A Alegado');
    expect(cr.venue).toBe('eLife');
    expect(cr.published?.toISOString()).toBe('2012-10-15T00:00:00.000Z');
    expect(cr.pdfUrl).toBe('https://cdn.elifesciences.org/articles/00013/elife-00013-v1.pdf');
    expect(cr.abstractHtml).toMatch(/^<p>Bacterially-produced small molecules/);
  });

  it('merges: abstract only when the landing page is thin', () => {
    const cr = parseCrossref(fixtureJson('crossref-elife.json').message, '10.7554/eLife.00013');
    const r = mergeDoi('10.7554/eLife.00013', cr, null);
    expect(r.type).toBe('paper');
    expect(r.html).toMatch(/^<section><h2>Abstract<\/h2><p>Bacterially-produced/);
    expect(r.author).toMatch(/ et al\.$/);
    expect(r.siteName).toBe('eLife');
    expect(r.paper).toMatchObject({ doi: '10.7554/eLife.00013', venue: 'eLife', year: 2012 });
    expect(r.canonicalUrl).toBe('https://doi.org/10.7554/eLife.00013');
  });

  it('extracts a DOI end to end with the landing page (mocked network)', async () => {
    const article = fixture('article.html');
    mockFetch([
      ['https://api.crossref.org/works/10.7554%2FeLife.00013', { body: fixture('crossref-elife.json'), type: 'application/json' }],
      ['https://doi.org/10.7554/eLife.00013', { body: article }],
    ]);
    const r = await extractUrl('https://doi.org/10.7554/eLife.00013');
    expect(r.type).toBe('paper');
    expect(r.title).toMatch(/^A bacterial sulfonolipid/);
    expect(r.html).toContain('<section><h2>Abstract</h2>');
    expect(r.html).toContain('There is a particular pleasure');
    // og:image is relative and the mocked response has no redirect, so it resolves against doi.org
    expect(r.imageUrl).toBe('https://doi.org/images/lead.jpg');
  });

  it('errors when neither Crossref nor the landing page work', async () => {
    mockFetch([]);
    await expect(extractUrl('10.9999/does-not-exist')).rejects.toThrow('Could not resolve DOI 10.9999/does-not-exist');
  });
});
